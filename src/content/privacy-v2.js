export function placeholders() {
  const out = [];
  const scan = (label, s) => { for (const m of String(s || '').matchAll(/\{\{[^}]*\}\}/g)) out.push({ where: label, text: m[0] }); };
  scan('META', Object.values(PRIVACY_META).join(' '));
  for (const a of ARTICLES) { scan(a.title, a.body); scan(a.title, a.bodyAfter); if (a.table) for (const r of a.table.rows) scan(a.title, r.join(' ')); }
  scan(APPENDIX.title, APPENDIX.body);
  for (const h of PRIVACY_HISTORY) scan('개정 이력', `${h.announcedAt} ${h.effectiveAt}`);
  return out;
}
