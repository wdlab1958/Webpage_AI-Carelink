export function toPlainText() {
  const lines = [`AI CareLink 서비스 이용약관 (v${TERMS_META.version} · 공고 ${TERMS_META.announcedAt} · 시행 ${TERMS_META.effectiveAt})`, '', COMPANY_LINE, ''];
  for (const ch of CHAPTERS) {
    lines.push(ch.title, '');
    for (const a of ch.articles) {
      if (a.title !== ch.title) lines.push(a.title);
      lines.push(a.body);
      if (a.table) { lines.push(a.table.head.join(' | ')); for (const r of a.table.rows) lines.push(r.join(' | ')); }
      if (a.bodyAfter) lines.push(a.bodyAfter);
      lines.push('');
    }
  }
  lines.push('개정 이력');
  for (const h of REVISION_HISTORY) lines.push(`v${h.version} (${h.announcedAt} 공고 · ${h.effectiveAt} 시행) — ${h.summary}`);
  return lines.join('\n');
}

